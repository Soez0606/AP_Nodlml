            <div style="display: flex; align-items: center; gap: 0.5em;">
                <span>📐</span>
                <h2 class="gradient-text">Mathématiques appliquées à l’informatique</h2>
            </div>

            <p>
                NoodleML met en œuvre les notions clés du programme de Mathématiques pour
                l’informatique du BTS SIO, en les illustrant par des situations concrètes de développement
                d’IA.
            </p>
            <ul>
                <li>Logique booléenne : les fonctions OR, AND et XOR permettent de relier directement
                    les tables de vérité aux réseaux de neurones.</li>
                <li>Algèbre linéaire : les poids d’un neurone modélisent une combinaison linéaire,
                    visualisable en 2D ou 3D.</li>

            </ul>
            UF2 (unité facultative):
            <ul>
                <li>Étude de fonction : mobilisation des notions de courbe, de symétrie, de minimum et
                    d’erreur.</li>
                <li>Dérivées : la rétropropagation repose sur le calcul de dérivées pour corriger les
                    erreurs du réseau.</li>
                <li>Statistiques : l'erreur quadratique moyenne (MSE) est suivie à chaque itération de
                    l’apprentissage.</li>
            </ul>
            <p>
                Ces éléments renforcent le lien entre raisonnement mathématique, algorithmique et développement
                logiciel, dans un cadre applicatif motivant.
            </p>
        </div>
