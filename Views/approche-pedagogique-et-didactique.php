                NoodleML mobilise des compétences issues des trois blocs du BTS SIO, option B Solutions
                Logicielles et Applications Métiers.
            </p>

            <ul>
                <li>
                    Bloc 1 – Support et mise à disposition de services informatiques<br>
                    → Analyse du besoin, lecture de cahier des charges, production de documentation technique.<br>
                    <em>Exemple : lecture d’une fonction cible pour l’entraînement d’un réseau de neurones.</em>
                </li>

                <li>
                    Bloc 2 – Conception et développement d’applications<br>
                    → Modélisation objet, architecture logicielle, développement front-end, structuration en
                    composants.<br>
                    <em>Exemple : conception MVC du framework, développement en JavaScript natif ou C++, interface
                        interactive via canvas.</em>
                </li>

                <li>
                    Bloc 3 – Cybersécurité des services informatiques<br>
                    → Prise en compte des risques, mise en place de bonnes pratiques, veille sur les vulnérabilités.<br>
                    <em>Exemple : sensibilisation aux usages de l’IA dans la détection d’anomalies ou la sécurisation
                        des flux.</em>
                </li>
            </ul>

            <p>
                Les démonstrations proposées peuvent être mobilisées dans le cadre :
            </p>
            <ul>
                <li>de projets d’ateliers de professionnalisation (développement, analyse, test d’une
                    solution applicative)</li>
                <li>de dossiers professionnels pour l’épreuve E4 (conception,
                    développement, documentation)</li>
                <li>de stages ou d’activités en autonomie autour de l’intelligence
                    artificielle et des IHM</li>
            </ul>



            <p>
                Au-delà de la seule logique applicative, l’intelligence artificielle s’impose comme une compétence
                transverse,
                y compris dans des domaines stratégiques comme la cybersécurité. L’usage de modèles simples pour
                détecter
                des anomalies, des comportements suspects ou automatiser des diagnostics constitue un prolongement
                naturel des
                acquis développés avec le framework, dans une logique de veille et d’innovation.
            </p>

