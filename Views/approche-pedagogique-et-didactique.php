            <div style="display: flex; align-items: center; gap: 0.5em;">
                <span>⚖️</span>
                <h2 class="gradient-text">Enjeux CEJM & cadre juridique de l’IA</h2>
            </div>

            <p>
                Le développement de solutions basées sur l’intelligence artificielle, même simples comme celles
                proposées par NoodleML, s’inscrit dans un cadre économique, éthique et juridique en pleine
                structuration.
            </p>

            <ul>
                <li><strong>Respect du RGPD</strong> : toute application d’IA manipulant des données personnelles impose
                    une réflexion sur la confidentialité, la sécurité et la transparence des traitements.</li>
                <li><strong>Responsabilité algorithmique</strong> : un algorithme mal conçu ou mal interprété peut
                    conduire à des biais, des décisions erronées ou discriminatoires.</li>
                <li><strong>Propriété intellectuelle</strong> : les modèles entraînés, les jeux de données ou le code
                    source relèvent du droit d’auteur et des licences logicielles (ex. : <code>GNU GPL v3</code> dans le
                    cadre de NoodleML).</li>
                <li><strong>Impact sur l’organisation</strong> : l’introduction d’une IA dans une entreprise modifie les
                    processus métiers, la gestion des ressources et les compétences attendues.</li>
                <li><strong>Responsabilité civile</strong> : selon l’article 1242 du Code civil, « on est responsable
                    non seulement
                    du dommage que l’on cause par son propre fait, mais encore de celui qui est causé par le fait des
                    choses
                    que l’on a sous sa garde ». Cela soulève une question juridique fondamentale : l’IA est-elle une
                    chose ?
                    Peut-on en avoir la garde, malgré son autonomie ? Le droit devra clarifier cette zone grise en
                    matière
                    de responsabilité et de réparation.</li>
            </ul>

            <h3>L'IA Act : un cadre européen pionnier</h3>
            <p>
                À l’échelle européenne, le règlement IA Act introduit un cadre légal inédit pour
                encadrer le développement et l’usage des intelligences artificielles. Son approche repose sur une
                classification des IA selon leur niveau de risque :
            </p>
            <ul>
                <li><strong>Risque inacceptable</strong> : interdit (ex. : notation sociale automatisée)</li>
                <li><strong>Risque élevé</strong> : strictement encadré (ex. : recrutement, éducation, santé)</li>
                <li><strong>Risque limité</strong> : obligations de transparence (ex. : chatbot)</li>
                <li><strong>Risque minimal</strong> : usage libre (ex. : jeux vidéo, filtres photo)</li>
            </ul>

            <p>
                Ce règlement engage les développeurs à documenter, expliquer et maîtriser les comportements de
                leur IA. Même dans un cadre scolaire, il prépare les futurs professionnels à coder
                avec responsabilité.
            </p>

            <p>
                Ces notions croisent directement les attendus de la Culture Économique, Juridique et
                Managériale (CEJM) du BTS SIO, notamment à travers la question :
                <em>« Quelle réponse apporte le droit face aux risques auxquels s’expose l’entreprise ? »</em>.
                Elles encouragent une vision globale de l’IA : utile, éthique et conforme au droit.
            </p>

