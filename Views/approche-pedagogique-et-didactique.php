                <h2 class="gradient-text">Dimension pédagogique</h2>
            </div>

            <h3>Objectif</h3>
            <p>Renforcer l’engagement, l’autonomie et la
                compréhension active des concepts d’IA.
            </p>

            <h3>Approche JavaScript & C++</h3>
            <p>
                Deux implémentations complémentaires :
            </p>
            <ul>
                <li>
                    JavaScript : la version utilisée dans le navigateur permet une
                    <em>interactivité immédiate</em>, idéale pour explorer visuellement les concepts.
                    Elle s'appuie sur canvas, des sliders HTML, et une architecture MVC claire.
                    Les apprenants expérimentent, observent et comprennent sans compilation.
                </li>
                <li>
                    C++ : la version native permet d'<em>approfondir la logique algorithmique</em>
                    d’un réseau de neurones en environnement organisationnel à forte contrainte (gestion mémoire,
                    resources limités, etc). Elle repose sur une structure orientée objet rigoureuse avec gestion fine
                    de la mémoire et des performances.

                </li>
            </ul>
            <p>
                Cette double approche permet de répondre à deux objectifs :
            </p>
            <ul>
                <li>offrir un accès rapide et ludique à l’IA via JavaScript (initiation, démonstration,
                    web
                    interactif)</li>
                <li>assurer une maîtrise technique avancée via C++ (back-end, algorithmique, dossiers
                    SLAM)
                </li>
            </ul>

            <h3>Design visuel</h3>
            <ul>
                <li>Style graphique manga : ce choix constitue un levier d’engagement pédagogique, en
                    s’appuyant sur des codes culturels contemporains pour renforcer la mémorisation, faciliter l’accès
                    aux notions abstraites et soutenir la motivation des apprenants.</li>
                <li>Nooden : mascotte engageante pour la mémorisation et la narration pédagogique.</li>
                <li>Minimalisme : lisibilité maximale, focus sur les concepts essentiels.</li>
                <li>Exploration ludique : interface manipulable favorisant
                    l’expérimentation.</li>
            </ul>

            <h3>Tonalité éditoriale assumée</h3>
            <p>
                Le projet adopte une tonalité éditoriale volontairement imagée et incarnée.
                Inspirée des codes narratifs des jeux vidéo, des récits initiatiques et de l’univers manga, cette
                approche vise à :
            </p>
            <ul>
                <li>Donner vie aux concepts abstraits en les rendant visuellement et narrativement
                    accessibles</li>
                <li>Favoriser l’engagement des apprenants en les immergeant dans un univers ludique,
                    mais rigoureux</li>
                <li>Dédramatiser la technique en brisant la distance avec le langage informatique</li>
            </ul>
            <p>
                La tonalité, loin d’être un simple habillage, participe pleinement à la pédagogie du sujet.
            </p>

